begin;

-- ---------- approved company on profile ----------
alter table public.profiles
  add column if not exists approved_company_name text;

alter table public.profiles
  add column if not exists company_updated_at timestamptz;

-- Snapshot company on public content so public pages never need profile-table reads.
alter table public.builds
  add column if not exists author_company text;

alter table public.build_comments
  add column if not exists author_company text;

-- ---------- company requests ----------
create table if not exists public.company_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  requested_company text not null,
  current_company text,
  current_name text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null
);

create index if not exists company_requests_user_created_idx_v115
  on public.company_requests(user_id, created_at desc);

create unique index if not exists company_requests_one_pending_v115
  on public.company_requests(user_id)
  where status = 'pending';

alter table public.company_requests enable row level security;

drop policy if exists axe_company_own_or_admin_read_v115
  on public.company_requests;

create policy axe_company_own_or_admin_read_v115
  on public.company_requests
  for select
  to authenticated
  using (
    user_id = auth.uid()
    or public.axe_hub_is_admin(auth.uid())
  );

grant select on public.company_requests to authenticated;
grant usage, select on sequence public.company_requests_id_seq to authenticated;

-- ---------- request company ----------
create or replace function public.request_company_name(
  p_requested_company text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_company text := btrim(p_requested_company);
  v_id bigint;
begin
  if auth.uid() is null then
    raise exception 'login required';
  end if;

  if char_length(v_company) < 2 or char_length(v_company) > 24 then
    raise exception '회사명은 2~24자여야 합니다.';
  end if;

  if v_company ~ E'[\r\n\t]' then
    raise exception '회사명에는 줄바꿈이나 탭을 사용할 수 없습니다.';
  end if;

  delete from public.company_requests
   where user_id = auth.uid()
     and status = 'pending';

  insert into public.company_requests(
    user_id,
    requested_company,
    current_company,
    current_name
  )
  select
    auth.uid(),
    v_company,
    approved_company_name,
    coalesce(approved_nickname, display_name, 'Discord User')
  from public.profiles
  where id = auth.uid()
  returning id into v_id;

  if v_id is null then
    insert into public.company_requests(
      user_id,
      requested_company,
      current_company,
      current_name
    )
    values (
      auth.uid(),
      v_company,
      null,
      'Discord User'
    )
    returning id into v_id;
  end if;

  return v_id;
end;
$$;

grant execute on function public.request_company_name(text)
  to authenticated;

-- ---------- review company ----------
create or replace function public.review_company_request(
  p_request_id bigint,
  p_approve boolean,
  p_admin_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.company_requests%rowtype;
begin
  if not public.axe_hub_is_admin(auth.uid()) then
    raise exception 'admin only';
  end if;

  select *
    into r
    from public.company_requests
   where id = p_request_id
   for update;

  if r.id is null then
    raise exception 'request not found';
  end if;

  if r.status <> 'pending' then
    raise exception 'already reviewed';
  end if;

  if p_approve then
    update public.profiles
       set approved_company_name = r.requested_company,
           company_updated_at = now()
     where id = r.user_id;

    -- Existing public content follows the newly approved company immediately.
    update public.builds
       set author_company = r.requested_company
     where author_id = r.user_id;

    update public.build_comments
       set author_company = r.requested_company
     where user_id = r.user_id;

    update public.company_requests
       set status = 'approved',
           admin_note = p_admin_note,
           reviewed_at = now(),
           reviewed_by = auth.uid()
     where id = r.id;
  else
    update public.company_requests
       set status = 'rejected',
           admin_note = p_admin_note,
           reviewed_at = now(),
           reviewed_by = auth.uid()
     where id = r.id;
  end if;
end;
$$;

grant execute on function public.review_company_request(bigint, boolean, text)
  to authenticated;

-- Backfill snapshots if any profiles already contain company data.
update public.builds b
   set author_company = p.approved_company_name
  from public.profiles p
 where b.author_id = p.id
   and p.approved_company_name is not null
   and b.author_company is distinct from p.approved_company_name;

update public.build_comments c
   set author_company = p.approved_company_name
  from public.profiles p
 where c.user_id = p.id
   and p.approved_company_name is not null
   and c.author_company is distinct from p.approved_company_name;

notify pgrst, 'reload schema';

commit;
