-- ---------- admin helper ----------
create or replace function public.axe_hub_is_admin(p_uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select is_admin from public.profiles where id = p_uid), false);
$$;

revoke all on function public.axe_hub_is_admin(uuid) from public;
grant execute on function public.axe_hub_is_admin(uuid) to anon, authenticated;

