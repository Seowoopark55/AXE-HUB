create or replace function public.refresh_build_vote_counts_v110(p_build_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update public.builds b
     set like_count = (select count(*) from public.build_votes v where v.build_id = p_build_id and v.value = 1),
         dislike_count = (select count(*) from public.build_votes v where v.build_id = p_build_id and v.value = -1)
   where b.id = p_build_id;
$$;

create or replace function public.build_votes_sync_counts_v110()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('UPDATE','DELETE') then perform public.refresh_build_vote_counts_v110(old.build_id); end if;
  if tg_op in ('INSERT','UPDATE') then perform public.refresh_build_vote_counts_v110(new.build_id); end if;
  return null;
end;
$$;

drop trigger if exists build_votes_sync_counts_v110 on public.build_votes;
create trigger build_votes_sync_counts_v110 after insert or update or delete on public.build_votes for each row execute function public.build_votes_sync_counts_v110();

create or replace function public.set_build_vote(p_build_id uuid, p_value smallint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if p_value not in (-1, 0, 1) then raise exception 'invalid vote'; end if;
  if p_value = 0 then
    delete from public.build_votes where build_id = p_build_id and user_id = auth.uid();
  else
    insert into public.build_votes(build_id, user_id, value)
    values (p_build_id, auth.uid(), p_value)
    on conflict (build_id, user_id) do update set value = excluded.value, updated_at = now();
  end if;
end;
$$;
grant execute on function public.set_build_vote(uuid, smallint) to authenticated;

