create or replace function public.request_nickname(p_requested_name text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := btrim(p_requested_name);
  v_id bigint;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  if char_length(v_name) < 2 or char_length(v_name) > 16 then raise exception '닉네임은 2~16자여야 합니다.'; end if;
  if v_name !~ '^[가-힣A-Za-z0-9 _-]+$' then raise exception '닉네임에는 한글, 영문, 숫자, 공백, _, - 만 사용할 수 있습니다.'; end if;
  if exists (select 1 from public.profiles where approved_nickname is not null and lower(approved_nickname) = lower(v_name) and id <> auth.uid()) then raise exception '이미 사용 중인 닉네임입니다.'; end if;
  delete from public.nickname_requests where user_id = auth.uid() and status = 'pending';
  insert into public.nickname_requests(user_id, requested_name, current_name)
  select auth.uid(), v_name, coalesce(approved_nickname, display_name, 'Discord User')
  from public.profiles where id = auth.uid()
  returning id into v_id;
  if v_id is null then
    insert into public.nickname_requests(user_id, requested_name, current_name) values (auth.uid(), v_name, 'Discord User') returning id into v_id;
  end if;
  return v_id;
end;
$$;
grant execute on function public.request_nickname(text) to authenticated;

create or replace function public.review_nickname_request(p_request_id bigint, p_approve boolean, p_admin_note text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.nickname_requests%rowtype;
begin
  if not public.axe_hub_is_admin(auth.uid()) then raise exception 'admin only'; end if;
  select * into r from public.nickname_requests where id = p_request_id for update;
  if r.id is null then raise exception 'request not found'; end if;
  if r.status <> 'pending' then raise exception 'already reviewed'; end if;

  if p_approve then
    if exists (select 1 from public.profiles where approved_nickname is not null and lower(approved_nickname) = lower(r.requested_name) and id <> r.user_id) then raise exception '이미 사용 중인 닉네임입니다.'; end if;
    update public.profiles set approved_nickname = r.requested_name, nickname_updated_at = now() where id = r.user_id;
    update public.builds set author_name = r.requested_name where author_id = r.user_id;
    update public.build_comments set author_name = r.requested_name where user_id = r.user_id;
    update public.nickname_requests set status = 'approved', admin_note = p_admin_note, reviewed_at = now(), reviewed_by = auth.uid() where id = r.id;
  else
    update public.nickname_requests set status = 'rejected', admin_note = p_admin_note, reviewed_at = now(), reviewed_by = auth.uid() where id = r.id;
  end if;
end;
$$;
grant execute on function public.review_nickname_request(bigint, boolean, text) to authenticated;

